package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"github.com/johnniewhite/ssher/internal/store"
	"github.com/johnniewhite/ssher/internal/ui"
)

var (
	exportCfgOutput string
	exportCfgAppend bool
)

var exportConfigCmd = &cobra.Command{
	Use:   "export-config",
	Short: "Export servers as ~/.ssh/config-style entries",
	Long: `Generates an OpenSSH client_config snippet from the saved servers.

By default writes to stdout. With --output <path>, writes to that file.
With --append, appends to the file (or stdout) instead of overwriting.

Passwords are not exported — OpenSSH config has no notion of stored passwords,
so those servers will fall back to the system's normal SSH auth flow.`,
	RunE: func(c *cobra.Command, args []string) error {
		saved, err := ui.LoadVault()
		if err != nil {
			return err
		}
		text := renderSSHConfig(saved.Vault.SortedServers(), saved.Vault.Aliases)

		switch {
		case exportCfgOutput == "":
			_, err = fmt.Print(text)
			return err
		case exportCfgAppend:
			f, err := os.OpenFile(exportCfgOutput, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
			if err != nil {
				return err
			}
			if err := f.Chmod(0o600); err != nil {
				_ = f.Close()
				return err
			}
			if _, err := fmt.Fprint(f, text); err != nil {
				_ = f.Close()
				return err
			}
			if err := f.Close(); err != nil {
				return err
			}
			fmt.Println(ui.Successf(fmt.Sprintf("appended to %s", exportCfgOutput)))
		default:
			if err := os.MkdirAll(filepath.Dir(exportCfgOutput), 0o700); err != nil {
				return err
			}
			f, err := openPrivateOutput(exportCfgOutput)
			if err != nil {
				return err
			}
			if _, err := f.WriteString(text); err != nil {
				_ = f.Close()
				return err
			}
			if err := f.Close(); err != nil {
				return err
			}
			fmt.Println(ui.Successf(fmt.Sprintf("wrote %s", exportCfgOutput)))
		}
		return nil
	},
}

func init() {
	exportConfigCmd.Flags().StringVarP(&exportCfgOutput, "output", "o", "", "write to FILE instead of stdout")
	exportConfigCmd.Flags().BoolVar(&exportCfgAppend, "append", false, "append to FILE instead of overwriting")
	rootCmd.AddCommand(exportConfigCmd)
}

func renderSSHConfig(servers []store.Server, aliases map[string]string) string {
	var b strings.Builder
	b.WriteString("# Generated by ssher\n\n")
	for _, s := range servers {
		var serverAliases []string
		for alias, target := range aliases {
			if target == s.Name {
				serverAliases = append(serverAliases, alias)
			}
		}
		sort.Strings(serverAliases)
		hostPatterns := append([]string{s.Name}, serverAliases...)
		fmt.Fprintf(&b, "Host %s\n", strings.Join(hostPatterns, " "))
		fmt.Fprintf(&b, "    HostName %s\n", s.Host)
		fmt.Fprintf(&b, "    User %s\n", s.User)
		if s.Port != 0 && s.Port != 22 {
			fmt.Fprintf(&b, "    Port %d\n", s.Port)
		}
		if s.AuthType == store.AuthKey && s.KeyPath != "" {
			fmt.Fprintf(&b, "    IdentityFile %s\n", s.KeyPath)
		}
		if s.JumpHost != "" {
			fmt.Fprintf(&b, "    ProxyJump %s\n", s.JumpHost)
		}
		if s.X11Forward {
			fmt.Fprintf(&b, "    ForwardX11 yes\n")
		}
		if s.KeepAlive > 0 {
			fmt.Fprintf(&b, "    ServerAliveInterval %d\n", s.KeepAlive)
		}
		for _, fw := range s.LocalForwards {
			fmt.Fprintf(&b, "    LocalForward %d %s:%d\n", fw.LocalPort, fw.RemoteHost, fw.RemotePort)
		}
		for _, fw := range s.RemoteForwards {
			fmt.Fprintf(&b, "    RemoteForward %d %s:%d\n", fw.LocalPort, fw.RemoteHost, fw.RemotePort)
		}
		customKeys := make([]string, 0, len(s.CustomOptions))
		for key := range s.CustomOptions {
			customKeys = append(customKeys, key)
		}
		sort.Strings(customKeys)
		for _, key := range customKeys {
			fmt.Fprintf(&b, "    %s %s\n", key, s.CustomOptions[key])
		}
		b.WriteByte('\n')
	}
	return b.String()
}
